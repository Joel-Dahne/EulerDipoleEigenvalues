#!/usr/bin/env python3
"""Generate a Markdown status report from checked blueprint source metadata.

No Lean or web build is required. Completion markers are reported as written;
they are not an audit of Lean declarations, axioms or mathematical correctness.
"""

import argparse
from collections import defaultdict
import os
from pathlib import Path
import sys
from urllib.parse import quote

from check_blueprint import Blueprint, NodeMetadata, check_blueprint

SECTORS = (
    ("Even–even", "thm:ee-exclusion", "even-even"),
    ("Odd–odd", "thm:dd-exclusion", "odd-odd"),
    ("Mixed", "thm:mixed-exclusion", "mixed"),
)


def closure(blueprint: Blueprint, target: str) -> set[str]:
    """Include the target and both statement/proof prerequisites, once each."""
    if target not in blueprint.nodes:
        raise ValueError(f"report target {target!r} is not a blueprint graph node")
    seen, todo = set(), [target]
    while todo:
        node = todo.pop()
        if node not in seen:
            seen.add(node)
            todo.extend(blueprint.dependencies.get(node, {}))
    return seen


def remaining(metadata: NodeMetadata) -> bool:
    if metadata.mathlibok:
        return False
    if metadata.kind == "definition":
        return not metadata.statement_leanok
    return not (metadata.statement_leanok and metadata.proof_leanok)


def counts(blueprint: Blueprint, labels: set[str]) -> dict[str, int]:
    metadata = [blueprint.metadata[label] for label in labels]
    definitions = [m for m in metadata if m.kind == "definition"]
    results = [m for m in metadata if m.kind != "definition"]
    return {
        "nodes": len(metadata),
        "definitions": len(definitions),
        "results": len(results),
        "statements": sum(m.statement_leanok for m in metadata),
        "proofs": sum(m.proof_leanok for m in results),
        "mathlib": sum(m.mathlibok for m in metadata),
        "remaining_results": sum(remaining(m) for m in results),
        "remaining_definitions": sum(remaining(m) for m in definitions),
    }


def quantity(count: int, noun: str) -> str:
    return f"{count} {noun}{'' if count == 1 else 's'}"


def table_text(value: str) -> str:
    return value.replace("|", r"\|").replace("\n", " ")


def source_link(blueprint: Blueprint, label: str, base: Path) -> str:
    location = blueprint.nodes[label]
    path = quote(Path(os.path.relpath(location.path.resolve(), base.resolve())).as_posix())
    return f"[`{table_text(label)}`]({path}#L{location.line})"


def render_report(blueprint: Blueprint, base: Path, sectors=SECTORS) -> str:
    """Render deterministically; base is the directory holding the Markdown file."""
    scopes = [(name, target, anchor, closure(blueprint, target))
              for name, target, anchor in sectors]
    source = (blueprint.source or Path("blueprint/src")) / "content.tex"
    source_path = quote(Path(os.path.relpath(source.resolve(), base.resolve())).as_posix())
    lines = [
        "<!-- Generated by scripts/blueprint_status.py; do not edit. -->",
        "# Generated blueprint status", "",
        "Regenerate with `just status-blueprint` (also run by `just web`).",
        "This saved report is a snapshot; regenerate after source edits.",
        f"Sources: [content.tex]({source_path}) and its recursive inputs.", "",
        "**Blueprint metadata only.** A marked proof may depend on admitted inputs.",
        "This report does not inspect Lean declarations or axioms, verify the",
        "annotations, or certify the mathematics. Counts are blueprint nodes, not",
        "distinct Lean declarations or analytic gaps. Handwritten priorities remain",
        "in `STATUS.md` and `docs/status/`.", "",
        "## Summary", "",
        "| Scope | Nodes | Definitions | Results | Statements marked | Result proofs marked | Mathlib |",
        "|---|---:|---:|---:|---:|---:|---:|",
    ]
    rows = [("All source nodes", set(blueprint.nodes))]
    rows.extend((f"[{name}](#{anchor})", labels) for name, _, anchor, labels in scopes)
    for name, labels in rows:
        c = counts(blueprint, labels)
        values = [c[key] for key in ("nodes", "definitions", "results", "statements", "proofs", "mathlib")]
        lines.append(f"| {name} | " + " | ".join(map(str, values)) + " |")
    lines.extend([
        "",
        r"- **Statements marked:** `\leanok` in statements, including definitions.",
        r"- **Result proofs marked:** `\leanok` in result proof environments; definitions are excluded.",
        r"- **Mathlib:** statement `\mathlibok` markers, counted separately (not added to either Lean-marker column).",
        "- Sector scopes include the target and its transitive prerequisites,",
        "  through both statement and proof dependencies. Shared nodes count once",
        "  per scope; sector counts must not be added together.",
        "",
        "## How to read unfinished nodes", "",
        r"A result remains listed if its statement or proof lacks `\leanok`, unless",
        r"the statement has `\mathlibok`. A definition needs only its statement marker.",
        r"A `\lean{...}` link alone does not count as a statement-completion marker.",
        r"The `\notready` flag is shown independently, without overriding other markers.",
        "Unmarked proof environments may contain paper proofs or sketches; absence",
        "of a completion marker does not mean absence of a written argument.",
    ])
    for name, target, anchor, labels in scopes:
        c = counts(blueprint, labels)
        lines.extend([
            "", f'<a id="{anchor}"></a>', f"## {name}", "",
            f"Target: {source_link(blueprint, target, base)} (included in this scope).", "",
            f"**Remaining:** {quantity(c['remaining_results'], 'result')} and "
            f"{quantity(c['remaining_definitions'], 'definition')}.",
        ])
        grouped = defaultdict(list)
        for label in blueprint.nodes:  # Document order, not alphabetical order.
            if label in labels and remaining(blueprint.metadata[label]):
                grouped[blueprint.metadata[label].chapter].append(label)
        if not grouped:
            lines.extend(["", "No unfinished nodes according to these markers."])
        chapter_order = [None, *blueprint.chapters]
        for chapter in chapter_order:
            pending = grouped.get(chapter, [])
            if not pending:
                continue
            title = chapter.title.replace("--", "–") if chapter else "Unchaptered nodes"
            group_counts = counts(blueprint, set(pending))
            lines.extend([
                "", f"### {title}", "",
                f"{quantity(group_counts['results'], 'result')}, "
                f"{quantity(group_counts['definitions'], 'definition')}.", "",
                "| Node (source link) | Kind | Statement | Proof | Not ready |",
                "|---|---|---|---|---|",
            ])
            for label in pending:
                m = blueprint.metadata[label]
                statement = r"`\leanok`" if m.statement_leanok else "Unmarked"
                if m.kind == "definition":
                    proof = "Not required"
                elif m.proof_leanok:
                    proof = r"`\leanok`"
                else:
                    proof = "Unmarked" if m.has_proof else "No proof environment"
                lines.append(f"| {source_link(blueprint, label, base)} | {m.kind} | "
                             f"{statement} | {proof} | {'Yes' if m.notready else 'No'} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--src", type=Path, default=Path("blueprint/src"),
                        help="blueprint source directory (default: blueprint/src)")
    parser.add_argument("--output", type=Path,
                        help="write Markdown here instead of stdout; creates parent directories")
    args = parser.parse_args()
    blueprint = check_blueprint(args.src)
    if blueprint.errors:
        for error in blueprint.errors:
            print(error, file=sys.stderr)
        print("Status report not generated: blueprint consistency checks failed.", file=sys.stderr)
        return 1
    try:
        base = args.output.parent if args.output else Path.cwd()
        report = render_report(blueprint, base)
        if args.output:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(report, encoding="utf-8")
            print(f"Wrote {args.output}")
        else:
            print(report, end="")
    except (ValueError, OSError) as error:
        print(f"Status report not generated: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
